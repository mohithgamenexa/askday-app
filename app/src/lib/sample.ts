function mulberry32(seed: number) {
  return () => {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Each group walks through the questions in its own shuffled order. */
export function questionIndexFor(seed: number, day: number): number {
  const n = DEMO_QUESTIONS.length;
  const order = Array.from({ length: n }, (_, i) => i);
  const r = mulberry32(seed + Math.floor((day - 1) / n));
  for (let i = n - 1; i > 0; i--) {
    const j = Math.floor(r() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }
  return order[(day - 1) % n];
}

